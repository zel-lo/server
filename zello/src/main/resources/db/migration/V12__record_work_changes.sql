CREATE TABLE work_changes (
    id BIGINT NOT NULL AUTO_INCREMENT,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    project_id BIGINT NOT NULL,
    repository_id BIGINT NOT NULL,
    source_key VARCHAR(100) NOT NULL,
    issue_id BIGINT NULL,
    pull_request_id BIGINT NULL,
    patch_note_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    summary TEXT NULL,
    category VARCHAR(20) NOT NULL,
    status VARCHAR(30) NOT NULL,
    occurred_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_work_changes_source UNIQUE (project_id, source_key),
    CONSTRAINT fk_work_changes_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_work_changes_repository FOREIGN KEY (repository_id, project_id) REFERENCES repositories (id, project_id),
    CONSTRAINT fk_work_changes_issue FOREIGN KEY (issue_id, repository_id) REFERENCES issues (id, repository_id),
    CONSTRAINT fk_work_changes_pull FOREIGN KEY (pull_request_id, repository_id) REFERENCES pull_requests (id, repository_id),
    CONSTRAINT fk_work_changes_note FOREIGN KEY (patch_note_id, project_id) REFERENCES patch_notes (id, project_id),
    CONSTRAINT ck_work_changes_target CHECK ((issue_id IS NOT NULL AND pull_request_id IS NULL) OR (issue_id IS NULL AND pull_request_id IS NOT NULL)),
    CONSTRAINT ck_work_changes_category CHECK (category IN ('FEATURE', 'FIX', 'IMPROVE')),
    CONSTRAINT ck_work_changes_status CHECK (status IN ('COMPLETED', 'MERGED', 'REOPENED', 'ARCHIVED', 'CONSOLIDATED')),
    INDEX idx_work_changes_note (patch_note_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
